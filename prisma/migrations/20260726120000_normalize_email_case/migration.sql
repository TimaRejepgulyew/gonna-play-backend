-- ============================================================================
-- MANUAL DRAFT MIGRATION — normalize_email_case
-- ----------------------------------------------------------------------------
-- Приводит уже накопленные адреса почты к тому же виду, в каком их отныне
-- пишет и ищет приложение: нижний регистр без крайних пробелов
-- (src/utils/email.ts, применяется в UserRepository.getUserByEmail/createUser/
-- updateUser, AuthRepository.getUserByEmailWithSecret и IdentityRepository).
--
-- ЗАЧЕМ ЭТО ОБЯЗАТЕЛЬНО ВМЕСТЕ С ТОЙ ПРАВКОЙ. Уникальный индекс "users"."email"
-- в Postgres регистрозависим, и до сих пор половины среза расходились: вход
-- через провайдера искал владельца по приведённому значению, а регистрация
-- паролем писала адрес как пришёл. Человек, зарегистрированный как
-- 'Keeper@Example.com', провайдерским входом не находился и получал второй
-- аккаунт. Теперь поиск идёт только по приведённому значению — и без этой
-- миграции такой человек перестал бы находиться вовсе, то есть потерял бы вход.
--
-- СХЕМЫ НЕ МЕНЯЕТ. Ни одной колонки, ни одного индекса: только данные. Поэтому
-- расхождения с prisma/schema.prisma она не создаёт.
--
-- К живой базе автоматически НЕ применяется: запуск на проде — за человеком
-- (docs/wiki/conventions.md:59). На пустом тестовом контуре оба UPDATE
-- исполняются вхолостую, а проверка ниже не находит ни одного столкновения.
--
-- ПРОВЕРКА БЕЗОПАСНОСТИ (шаг 1). Приведение регистра способно столкнуть два
-- разных аккаунта в один адрес: 'Keeper@Example.com' и 'keeper@example.com'
-- сегодня лежат как разные строки, а после приведения станут одной, и
-- уникальный индекс UPDATE не пропустит. Сливать такие аккаунты или терять один
-- из них молча миграция не имеет права: это два разных набора матчей, рейтингов
-- и способов входа. Поэтому шаг 1 сначала ищет столкновения и, найдя хоть одно,
-- ОСТАНАВЛИВАЕТ миграцию с перечислением конфликтующих адресов и id.
--
-- ЧТО ДЕЛАТЬ, ЕСЛИ ПРОВЕРКА СРАБОТАЛА. Миграция откатится целиком, база
-- останется в прежнем состоянии — чинить надо данные, а не миграцию.
-- В сообщении об ошибке будут приведённый адрес и список "users"."id",
-- претендующих на него. По каждой группе нужно решением человека выбрать один
-- аккаунт-владельца и развести остальные ДО повторного запуска:
--   1) снять по каждому id признаки жизни (наличие пароля, строки в
--      "auth_identities", профиль игрока, матчи, дату последнего входа);
--   2) владельцем оставить живой аккаунт, а лишним либо обнулить почту
--      (UPDATE "users" SET "email" = NULL WHERE "id" = ...), либо перенести
--      данные во владельца вручную и удалить пустой аккаунт;
--   3) прогнать миграцию заново — проверка должна пройти молча.
-- Автоматически выбрать «наименьший id» здесь нельзя: в отличие от переноса
-- телеграмных привязок (20260725222805_add_auth_identity), где источником был
-- один и тот же внешний аккаунт, тут за одинаковым адресом могут стоять два
-- полноценных пользователя, и правильный ответ знает только человек.
--
-- ШАГ 3 (auth_identities) правится тем же правилом ради единообразия. Риска
-- столкновения там нет: уникален в этой таблице только (provider,
-- "providerUserId"), а "email" — справочная копия того, что отдал провайдер.
-- ============================================================================


-- Шаг 1: проверка безопасности. Останавливает миграцию, если приведение
-- регистра столкнуло бы два разных аккаунта в один адрес.
DO $$
DECLARE
    collisions text;
BEGIN
    SELECT string_agg(normalized || ' → users.id: ' || ids, '; ' ORDER BY normalized)
      INTO collisions
      FROM (
          SELECT lower(btrim("email")) AS normalized,
                 string_agg("id"::text, ', ' ORDER BY "id") AS ids
            FROM "users"
           WHERE "email" IS NOT NULL
           GROUP BY lower(btrim("email"))
          HAVING count(*) > 1
      ) AS grouped;

    IF collisions IS NOT NULL THEN
        RAISE EXCEPTION
            'normalize_email_case: приведение почты к нижнему регистру столкнуло бы разные аккаунты: %',
            collisions
            USING HINT = 'Разведите аккаунты вручную (оставьте владельца, остальным обнулите email) и запустите миграцию заново. Подробности — в шапке файла migration.sql.';
    END IF;
END
$$;

-- Шаг 2: приведение почты пользователей. Строки, уже лежащие в нужном виде,
-- не переписываются.
UPDATE "users"
   SET "email" = lower(btrim("email"))
 WHERE "email" IS NOT NULL
   AND "email" <> lower(btrim("email"));

-- Шаг 3: та же нормализация справочной копии адреса в способах входа.
UPDATE "auth_identities"
   SET "email" = lower(btrim("email"))
 WHERE "email" IS NOT NULL
   AND "email" <> lower(btrim("email"));
