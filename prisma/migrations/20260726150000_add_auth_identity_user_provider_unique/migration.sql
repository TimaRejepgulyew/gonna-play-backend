-- Переводит базу ОТ состояния после `20260726120000_normalize_email_case`
-- К инварианту, обеспеченному индексом: «одна запись на провайдера у
-- пользователя». У одного "users"."id" не может быть двух строк
-- "auth_identities" с одинаковым "provider".
--
-- ЧТО ЭТОТ ИНВАРИАНТ ЗАЩИЩАЕТ. Прежняя уникальность (provider,
-- "providerUserId") запрещает лишь привязку одного внешнего аккаунта к двум
-- пользователям и ничего не говорит о двух аккаунтах ОДНОГО провайдера у одного
-- человека. Проверка в сервисе (src/auth/identityLink.service.ts) читает список
-- привязок ДО вставки, поэтому два одновременных запроса на привязку одного
-- провайдера проходили её оба. Последствия записанного дубликата: отвязка
-- удаляет строки пачкой по ("userId", provider) и снесла бы обе разом, а выбор
-- долгоживущего refresh-токена Apple берётся первой подходящей строкой и стал
-- бы произвольным.
--
-- ЭТО РУЧНОЙ ЧЕРНОВИК. К живой базе НЕ применялся: запуск на проде — за
-- человеком (docs/wiki/conventions.md).
--
-- ЕСЛИ НА НЕПУСТОЙ БАЗЕ ИНДЕКС НЕ СОЗДАЁТСЯ. Отказ
-- `could not create unique index "auth_identities_userId_provider_key"`
-- означает, что дубликаты в таблице уже есть. Автоматической чистки здесь нет
-- намеренно: какая из строк настоящая — решение по данным, а не по схеме, и
-- удаление привязки необратимо (человек теряет способ входа). Порядок разбора:
--
--   1. Снять резервную копию таблицы:
--      CREATE TABLE auth_identities_backup AS TABLE auth_identities;
--   2. Найти группы дубликатов:
--      SELECT "userId", provider, count(*) AS rows, array_agg(id ORDER BY id)
--      FROM auth_identities
--      GROUP BY "userId", provider
--      HAVING count(*) > 1;
--   3. В каждой группе оставить одну строку: с непустым
--      "refreshTokenEncrypted" (иначе потеряется отзыв доступа Apple при
--      удалении аккаунта), при прочих равных — с самым свежим "lastLoginAt",
--      при равенстве — с наименьшим id.
--   4. Лишние строки удалить поштучно по id и повторить эту миграцию.
